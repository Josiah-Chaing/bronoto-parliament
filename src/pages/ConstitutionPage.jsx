const preamble = `序言

曩者威權獨裁，公權濫用，吾全體國民之自由、權利備受侵損。鑒往知來，引以為戒，白東民國全體國民同心相約：為守護自由、正義與和平，堅持主權在民之根本，締造民主、法治、平等、博愛之社會，特共同制定本憲法。吾全體國民鄭重宣示：矢志遠離戰禍、摒棄暴政，共建國民主權、權力分立之憲政秩序；以此根本大法為準繩，彼此相守權益，共保國基長存，同謀萬民安康。

第一章　總綱

第一條　白東民國為國民主權、地方分權之民主共和國。主權屬於全體國民。

第一條之一　白東民國為統一國家，領土不可分割。任何組織、團體或個人不得以任何形式分裂國家或危害國家主權、領土完整。此行為之認定與處置，應依法律為之；其涉及憲法爭議者，得依法聲請憲法法院審查。國家依法保障統一與穩定，並透過法律制度維護民族團結與國家完整。

第二條　本憲法為國家最高法，具有最高之法律效力。任何法律、命令、條約及地方規章等與本憲法牴觸者無效。一切國家權力之行使，均應以本憲法為最高依據。

第三條　國家元首為白東民國總統，為國家之象徵，代表國家行使憲法所定職權。總統應超越黨派，保持政治中立。

第四條　國家承認並保障國民之基本人權，尊重信仰、思想、言論及人格之自由。國家保障國民基本人權的實現，應採取適當措施，積極保障基本權利之實現。一切國家權力之行使，均受基本人權之拘束。

第五條　白東民國允許雙重國籍，相關規定由法律定之。雙重國籍國民在履行國家法定義務時，不得因國籍雙重性規避責任。國家對雙重國籍國民之管轄權，依法及國際法一般原則。相關細則由法律定之。

第六條　白東民國無國教，宗教自由受保障。

第七條　國旗為藍白旗幟，上藍下白，各占二分之一；國徽由盾形國旗、橄欖枝、交叉雙劍、智慧之眼、國花茉莉與刻有國名之徽帶組成。

第八條　首都為奉天。

第二章　國民權利與義務

第九條　白東民國國民之生命、自由及財產受憲法保障，非依法律不得剝奪。國民享有言論、講學、著作、出版、信仰、集會、結社、游行、示威、罷工、居住、遷徙、通訊自由與通訊秘密、個人信息保護及其他不妨害社會秩序與公共利益之自由與權利。

第九條之一　任何人非經法定程序，不得被逮捕、拘禁、處罰或剝奪人身自由。逮捕拘禁機關應於二十四小時內將被逮捕拘禁人移送法院審查，不得無故拖延。任何人受刑事追訴時，享有下列權利：一、無罪推定。二、選任辯護人。三、請求調查有利證據。四、詰問不利證人。五、不自證己罪。六、迅速公開審判。七、一事不再理。禁止對任何人施以酷刑、殘忍、不人道或侮辱性之待遇或處罰。

第十條　國民在法律上一律平等。國家不得因性別、種族、民族、語言、宗教、出生、身心障礙、性傾向或其他身份而予差別對待。

第十一條　國民享有選舉、罷免、創制及複決之權。前項權利之行使，由法律定之。國民享有依法向國家機關請願之權利。受理機關應於法定期限內處理並答覆請願人。

第十二條　國家應保障國民之基本生活、教育、醫療、養老與社會安全，建立普惠性社會保障體系，對弱勢群體給予特別保障。國家應保障國民之勞動權，包括同工同酬、安全衛生之工作環境、合理工時與休息、職業訓練及組織工會之權利。

第十三條　國家應保障生態安全與自然資源之永續利用，將環境保護納入國家發展之基本政策。

第十四條　國家應保障國民之文化權，尊重多元文化之發展，保護文化資產，促進學術自由與文化創作。

第十五條　國民有遵守憲法與法律、納稅、依法服志願兵役及依法維護國家與公共利益之義務。

第三章　國會

第十六條　國會為白東民國最高立法機關，由全國國民依法選舉之國會議員組成。國會代表全體國民行使立法權，為國家最高權力機關。

第十七條　國會之職權如下：一、制定、修改及廢止法律。二、審查國家預算及決算。三、審查及批准國際條約。四、對總理及各部首長提出質詢。五、對總統、總理及各部首長提出彈劾案。六、組織調查委員會，對特定事項進行調查。七、行使本憲法規定之其他職權。

第十八條　國會議員總額為五百名，由各選區依法選舉產生。選舉制度採小選舉區制與比例代表制並行，具體名額分配及選舉方式由法律定之。

第十九條　國會議員任期四年，連選得連任。國會議員在任期中享有言論免責權及不受逮捕之特權。

第二十條　國會設議長一人、副議長二人，由國會議員互選產生。議長對外代表國會，對內綜理國會會務。

第二十一條　國會每年至少舉行兩次常會。必要時，經全體國會議員四分之一以上之請求或總理之提請，得召開臨時會議。

第二十二條　國會設各專門委員會，負責審查法案、預算及特定事項。各專門委員會之組織及職權，由國會內規及法律定之。`;

